#!/bin/sh
# Builds the files of a release into dist/: a signed binary for each Mac
# architecture, zipped with the license and notices, their checksums, and
# the Homebrew formula that points at them. Nothing is uploaded.
#
# Usage: package.sh
#
# Signing is as in sign.sh. To have Apple notarize the binaries as well,
# store your credentials once under a profile name of your choosing:
#
#     xcrun notarytool store-credentials harbormaster-notary
#
# and run this with HARBORMASTER_NOTARY_PROFILE=harbormaster-notary. The
# credentials stay in your Keychain; this script only names the profile.
set -eu
cd "$(dirname "$0")/../.."

version="$(sed -n 's/^version = "\(.*\)"/\1/p' Cargo.toml | head -n 1)"
[ -n "$version" ] || { echo "could not read the version from Cargo.toml" >&2; exit 1; }
tag="v$version"
repo="${HARBORMASTER_REPO:-ultradotdev/harbormaster}"

identity="${HARBORMASTER_SIGN_IDENTITY:-}"
if [ -z "$identity" ]; then
  identity="$(security find-identity -v -p codesigning | sed -n 's/.*"\(Developer ID Application: [^"]*\)".*/\1/p' | head -n 1)"
fi
[ -n "$identity" ] || { echo "No Developer ID Application certificate found. Set HARBORMASTER_SIGN_IDENTITY." >&2; exit 1; }

. tools/release/flags.sh
rm -rf dist
mkdir -p dist
installed="$(rustup target list --installed 2>/dev/null || true)"

# package TARGET NAME: builds, signs and zips one architecture.
package() {
  target="$1"
  name="harbormaster-$tag-$2"
  cargo build --release --target "$target"
  stage="dist/$name"
  mkdir -p "$stage"
  cp "target/$target/release/harbormaster" LICENSE NOTICE README.md "$stage/"
  codesign --force --options runtime --timestamp --identifier dev.ultra.harbormaster --sign "$identity" "$stage/harbormaster"
  codesign --verify --strict "$stage/harbormaster"
  (cd "$stage" && zip -q -X "../$name.zip" harbormaster LICENSE NOTICE README.md)
  if [ -n "${HARBORMASTER_NOTARY_PROFILE:-}" ]; then
    xcrun notarytool submit "dist/$name.zip" --keychain-profile "$HARBORMASTER_NOTARY_PROFILE" --wait
  fi
  rm -rf "$stage"
}

package aarch64-apple-darwin darwin-arm64
if printf '%s\n' "$installed" | grep -qx x86_64-apple-darwin; then
  package x86_64-apple-darwin darwin-x64
else
  echo "Skipping Intel Macs: rustup target add x86_64-apple-darwin to include them." >&2
fi

(cd dist && shasum -a 256 harbormaster-*.zip > SHA256SUMS)
sum() { sed -n "s/^\([0-9a-f]*\)  harbormaster-$tag-$1\.zip\$/\1/p" dist/SHA256SUMS; }

# The formula, generated so that its checksums can never be stale.
arch_block() {
  [ -n "$(sum "$2")" ] || return 0
  cat <<BLOCK

    on_$1 do
      url "https://github.com/$repo/releases/download/$tag/harbormaster-$tag-$2.zip"
      sha256 "$(sum "$2")"
    end
BLOCK
}
{
  cat <<HEAD
# typed: strict
# frozen_string_literal: true

# Generated by tools/release/package.sh from the SHA256SUMS of the
# $repo $tag release. Do not edit: each release regenerates it.
class Harbormaster < Formula
  desc "HomeKit bridge for UniFi Protect cameras, doorbells and sensors"
  homepage "https://github.com/$repo"
  version "$version"
  license "Apache-2.0"

  depends_on "ffmpeg"
  depends_on :macos

  on_macos do
    depends_on macos: :sonoma
HEAD
  arch_block arm darwin-arm64
  arch_block intel darwin-x64
  cat <<'TAIL'
  end

  def install
    bin.install "harbormaster"
    doc.install "NOTICE", "README.md"
  end

  def caveats
    <<~EOS
      First run:
        harbormaster setup

      After an upgrade, have the service pick up the new version:
        harbormaster service install
    EOS
  end

  test do
    assert_match "harbormaster #{version}", shell_output("#{bin}/harbormaster --version")
  end
end
TAIL
} > dist/harbormaster.rb

echo
cat dist/SHA256SUMS
echo
echo "Release files are in dist/. To publish $tag:"
echo "  gh release create $tag dist/*.zip dist/SHA256SUMS --repo $repo --title $tag --generate-notes"
echo "  then copy dist/harbormaster.rb to Formula/harbormaster.rb in ultradotdev/homebrew-tap"
